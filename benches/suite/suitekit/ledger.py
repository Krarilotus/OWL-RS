"""`suite.py ledger`: the run records under benches/runs/, one TOML file per run.

A run record says what a run covered and how each pair came out, never how fast: the raw
results stay in the git-ignored results directory (some vendors forbid publishing them),
the record is committed. benches/STATUS.md is generated from the records
(`suite.py status`), so what has been measured, where and from which commit survives on
every machine.

    suite.py ledger RESULTS-DIR [RESULTS-DIR ...]   write or refresh their records
    suite.py ledger --all                           every directory under benches/suite/results

A directory of runs (a `fast.py compete` batch: one results directory per case) is one
record. A record's `versus` holds NRESE against each free comparator, case by case
(suitekit/versus.py: answers, then time with its interval, load, memory): what
benches/STANDINGS.md is made of. A licensed system's entries never enter a record.

Hand-written fields (purpose, baseline, findings, and commit or machine where a run
predates manifests) are kept when a record is refreshed. Records of kits outside the suite
(benches/reasoning/dl, the perf lab) are written by hand in the same format
(benches/runs/README.md).
"""
from __future__ import annotations

import argparse
import json
import re
import tomllib
from pathlib import Path

from .schema import read
from .summary import summarise

HAND_FIELDS = ("purpose", "baseline", "findings", "level", "scenario", "candidate", "inputs", "cases", "results")
FALLBACK_FIELDS = ("commit", "machine", "host", "started", "finished", "protocol")
ORDER = ["id", "level", "kit", "purpose", "started", "finished", "host", "machine", "scenario", "baseline",
         "candidate", "commit", "dirty", "protocol", "inputs", "commands", "results", "publishable", "cases",
         "findings", "versus"]


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        if not any(isinstance(v, (list, dict)) for v in value) and len(value) <= 4:
            return "[" + ", ".join(toml_value(v) for v in value) + "]"
        return "[\n" + "".join(f"  {toml_value(v)},\n" for v in value) + "]"
    if isinstance(value, dict):
        # A key that isn't bare (a receipt's repository path, /data input or image) is quoted; TOML
        # has no null, so a value not known (None) is left out: absent, never the string "None".
        return "{ " + ", ".join(f"{k if re.fullmatch(r'[A-Za-z0-9_-]+', k) else json.dumps(k)} = {toml_value(v)}"
                                for k, v in value.items() if v is not None) + " }"
    return json.dumps(str(value), ensure_ascii=False)


def dump(record: dict) -> str:
    lines = ["# A run record (benches/runs/README.md). Generated by `suite.py ledger` from the run's",
             "# results.csv and manifest.json; purpose, baseline and findings are written by hand",
             "# and kept when the record is refreshed. Outcomes only: the numbers stay local.", ""]
    for key in ORDER + [k for k in record if k not in ORDER and k != "pairs"]:
        if key in record and record[key] is not None:
            lines.append(f"{key} = {toml_value(record[key])}")
    lines.append("")
    lines.append("pairs = [")
    for pair in record.get("pairs", []):
        lines.append(f"  {toml_value({k: v for k, v in pair.items() if v not in ('', None)})},")
    lines.append("]")
    return "\n".join(lines) + "\n"


# The reset of 25 Oct 2026: refactor/engine-v2 started again from 59e5e24c and takes the earlier lines'
# work package by package (Harness notes, Sol-line integration). A record started before it measured an
# engine the current line doesn't continue as it was: its results stay, as history, marked wherever they
# are shown, never read as the current engine's; the v1.6 baseline measures the current one whole.
RESET_DATE, RESET_BASE = "2026-10-25", "59e5e24c"
PRE_RESET = "†"
PRE_RESET_NOTE = (f"{PRE_RESET} before the reset of 25 Oct 2026 (engine-v2 re-based on {RESET_BASE}): history, "
                  "not the current engine's result")


def pre_reset(record: dict) -> bool:
    """Whether the record was started before the reset (RESET_DATE); one without a start date is."""
    return str(record.get("started", ""))[:10] < RESET_DATE


def load_records(runs_dir: Path) -> list[dict]:
    records = []
    for path in sorted(runs_dir.glob("*.toml")):
        with open(path, "rb") as f:
            record = tomllib.load(f)
        record.setdefault("id", path.stem)
        records.append(record)
    return records


def run_directories(directory: Path) -> list[Path]:
    """The results directories a record covers: the directory, or the runs in it (a batch)."""
    if (directory / "results.csv").exists():
        return [directory]
    return sorted(d for d in directory.iterdir() if (d / "results.csv").exists())


def from_results(directory: Path, root: Path) -> dict:
    runs = run_directories(directory)
    rows, invocations = [], []
    for run in runs:
        # Runs of a batch number their repetitions alike: each keeps its own.
        rows += [r | {"run": f"{run.name}:{r['run']}"} if len(runs) > 1 else r for r in read(run / "results.csv")]
        if (run / "manifest.json").exists():
            invocations += json.loads((run / "manifest.json").read_text(encoding="utf-8")).get("invocations", [])
    try:
        shown = directory.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        shown = directory.name
    record: dict = {"id": directory.name, "kit": "suite", "results": f"{shown} (local, git-ignored)"}
    if invocations:
        invocations = sorted(invocations, key=lambda i: i.get("started") or "")
        first = invocations[0]
        record["started"] = first["started"]
        finished = [i.get("finished") for i in invocations]
        record["finished"] = max(finished) if all(finished) else "unfinished"
        m = first.get("machine", {})
        from . import hosts
        found = hosts.current(name=m.get("host", "")) if m.get("host") else None
        record["host"] = found[0] if found else m.get("host", "")
        docker = m.get("docker")
        record["machine"] = (f"{m.get('cpu')}, {m.get('logical_cores')} threads, {m.get('memory_gib')} GiB; "
                             f"{m.get('os')}" + (f"; Docker {docker['version']} ({docker['cpus']} CPUs, "
                                                 f"{docker['memory_gib']} GiB)" if docker else ""))
        commits = sorted({i["git"].get("commit") or "unknown" for i in invocations})
        record["commit"] = commits[0] if len(commits) == 1 else ", ".join(commits)
        record["dirty"] = max(i["git"].get("dirty", 0) for i in invocations)
        p = first["protocol"]
        record["protocol"] = (f"{p['runs']} runs, {p['query_runs']} measured query runs, cache {p['cache']}, "
                              f"order {p['order']} (seed {p['seed']}), load limit {p['timeout_s']} s, "
                              f"query limit {p['query_timeout_s']} s, {p['runtime']}")
        record["commands"] = list(dict.fromkeys("suite.py run " + " ".join(i["argv"]) for i in invocations))
    elif rows:
        record["started"] = rows[0]["date"]
        record["host"] = rows[0]["host"]
        record["commit"] = "unknown (before run manifests)"
    # Each cell's newest attempt (receipts.py), finished or not: never an older receipt in an
    # unfinished one's place, never the directory's commit, outcome or answers (review r1 R2, R3).
    newest: dict[str, dict] = {}
    for invocation in invocations:
        for cell, attempt in (invocation.get("cells") or {}).items():
            if cell not in newest or str(attempt.get("started", "")) >= str(newest[cell].get("started", "")):
                newest[cell] = attempt
    pairs, summarised = [], summarise(rows)
    for (workload, tier, system), pair in sorted(summarised.items()):
        entry = {"workload": workload, "tier": tier, "system": system} | pair.outcome()
        if (attempt := newest.get(f"{workload}/{tier}/{system}")) is not None:
            # A licensed system's outcome and answers are results, whatever the outcome: they stay
            # local (R1); its receipt says only what ran.
            entry["receipt"] = ({k: v for k, v in attempt.items() if k not in ("outcome", "answers")}
                                if pair.publish == "permission" else attempt)
        pairs.append(entry)
    record["pairs"] = pairs
    restricted = any(p.publish == "permission" for p in summarised.values())
    record["publishable"] = "free systems only" if restricted else "all"
    from . import cases
    from .versus import versus
    turfs = {c["name"]: c.get("home_turf", "") for c in cases.load(root / "benches/cases")}
    entries = versus(directory, turfs)
    record["versus"] = [{k: v for k, v in e.items() if k != "publish"} for e in entries if e["publish"] == "free"]
    return record


def refresh(directory: Path, root: Path, runs_dir: Path) -> Path:
    record = from_results(directory, root)
    path = runs_dir / f"{record['id']}.toml"
    if path.exists():
        with open(path, "rb") as f:
            old = tomllib.load(f)
        for key in HAND_FIELDS:
            if key in old:
                record[key] = old[key]
        for key in FALLBACK_FIELDS:
            if key in old and (key not in record or str(record[key]).startswith("unknown")):
                record[key] = old[key]
    for key, default in (("purpose", ""), ("baseline", ""), ("findings", [])):
        record.setdefault(key, default)
    runs_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(record), encoding="utf-8", newline="\n")
    return path


def main(argv: list[str], root: Path) -> int:
    p = argparse.ArgumentParser(prog="suite.py ledger", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("directories", nargs="*", type=Path, help="results directories")
    p.add_argument("--all", action="store_true", help="every directory under benches/suite/results")
    args = p.parse_args(argv)
    directories = list(args.directories)
    if args.all:
        directories += sorted(d for d in (root / "benches/suite/results").iterdir()
                              if (d / "results.csv").exists())
    if not directories:
        p.error("name results directories, or --all")
    for directory in directories:
        print(refresh(directory, root, root / "benches/runs").relative_to(root).as_posix())
    return 0
