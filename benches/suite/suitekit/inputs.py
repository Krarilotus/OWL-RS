"""Which external files a fast case loads: the one answer, for the runner that records their bytes
(fast.py case_inputs()) and the comparison that holds verdicts to them (compare.input_check()).

The orchestrator, 7 Nov 2026 (fix check r2 of pkg/stage-data): the recorder and the comparison had
each their own idea of an input (a `volume:` prefix, a size map, a generated-only exemption), and
each review found another gap. Here, a data spec (`data`, `data_alt`, `extra`, a concatenation's
parts) is one of:

- `none`: nothing;
- a generator spec (`KIND key=value ...`, its first word without a colon): generated by the code
  compared, its identity the spec itself, no external file;
- `volume:FILE`: a frozen dataset, keyed FILE;
- `ore:ID`: an ORE ontology as converted for the suite, keyed `ore:ID`;
- `concat:A+B`: its parts' inputs, and the concatenation itself, keyed by its spec (its parts in
  order: other bytes than the same parts in another order);
- any other `KIND:...`: external, of a kind nothing here resolves: declared, so its bytes are
  unknown and no verdict stands on it (a new kind fails closed until it is taught here).

A case's `reference` taxonomy is an external file too, keyed `reference:PATH`.
"""
from __future__ import annotations

import re

KIND = re.compile(r"^([A-Za-z0-9_.-]+):")
EXTERNAL = ("volume", "ore", "concat")


def kind(spec: str) -> str:
    """`none`, `generated`, `volume`, `ore`, `concat`, or `unknown` (an external kind not taught here)."""
    if not spec or spec == "none":
        return "none"
    match = KIND.match(spec)
    if match is None:
        return "generated"
    return match.group(1) if match.group(1) in EXTERNAL else "unknown"


def spec_keys(spec: str) -> list[str]:
    """The external inputs one data spec loads, by their keys (the module's docstring)."""
    k = kind(spec)
    if k in ("none", "generated"):
        return []
    if k == "volume":
        return [spec[len("volume:"):]]
    if k == "concat":
        return [key for part in spec[len("concat:"):].split("+") for key in spec_keys(part)] + [spec]
    return [spec]  # ore:ID, and an unknown kind: the spec itself


def specs(case: dict) -> list[str]:
    """A case's data specs: `data`, `data_alt`, `extra`."""
    return [case.get("data") or "none", *([case["data_alt"]] if case.get("data_alt") else []),
            *(case.get("extra") or [])]


def declared(case: dict) -> set[str]:
    """Every external file the case loads, by its key: what its records must hash, all of them."""
    out = {key for spec in specs(case) for key in spec_keys(spec)}
    if case.get("reference"):
        out.add(f"reference:{case['reference']}")
    return out
